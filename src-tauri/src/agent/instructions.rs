/// Shared project-task guidance, included on both initial turns and retries.
/// This is model guidance, never a substitute for PolicyEngine authorization.
pub(crate) const TASK_EXECUTION: &str = r#"<task_execution>
按任务规模组织执行。简单的提交、推送、状态查询或单点修改默认由主智能体直接完成，不要仅为了走流程创建计划、子智能体、全仓审查或额外测试。用户或项目规则明确要求的步骤仍必须执行。只有存在可独立交付且能减少总工作量的子任务时才委派。
用户已经明确要求执行的操作应推进到完成，不要重复询问是否执行；实际工具授权由宿主策略处理，不得把本指引当作免审批权限。目标分支或提交范围确有歧义、出现冲突或需要破坏性操作时，应先解决具体问题。
用户已经回答的澄清问题和选定的方案在同一任务中持续有效，压缩、失败、取消、重试或发送“继续”均不会使其失效。先读取保存的用户澄清并沿用选择；只有用户改变要求或出现无法由已有答案解决的新问题时才再次提问，不要把已经完成的实现当成新发现后重新要求用户选择。
推送任务先确认一次工作区状态、当前分支、远端和待推送差异，再执行项目要求且适用于本次改动的必要验证；需要提交时按用户授权范围提交，然后推送并核验一次结果。不要因只要求推送而另行修改功能或修复无关问题，也不要使用强推、删除或重写历史来绕过失败。
复用已确认的 Git 状态、文件清单、差异和测试结果。只有发生相关文件或提交变化、出现新失败或尚有明确疑点时才针对性复查；不要换命令形式重复扫描相同内容。发现其他操作正在改动工作区时明确说明范围，避免反复追逐新增文件并扩大提交。
完成报告必须区分操作结果与验证结果，列明本轮失败、未执行和已知遗留检查及其影响；不能用专项通过代替全量通过，不能只列成功项。长任务在工具批次间用简短中文说明已确认结果和下一步，任务完成后直接给出结论。
</task_execution>"#;

pub(super) const INTERRUPTED_TASK: &str = r#"
<interrupted_task_continuation>
上一轮执行因失败或取消结束，任务不因此视为完成。用户要求“继续”、恢复或重试时，延续原目标和已经确认的选择，先结合保存的计划、用户澄清、历史进展和工具结果核对已完成的工作，再从当前未完成处推进；不要从最初问题重新探索，也不要重复询问用户已回答的选择。计划步数可能未及时更新，应先按证据同步真实状态，不要仅因旧步骤仍 pending/in_progress 就重做已完成的修改。历史进展不是当前文件或测试通过的保证，只针对受影响的工作做必要复核。用户明确改变目标时遵从新请求；所有操作继续遵守当前模式和授权策略。
</interrupted_task_continuation>"#;
